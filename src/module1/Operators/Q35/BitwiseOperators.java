package module1.Operators.Q35;

public class BitwiseOperators {
    public static void main(String[] args) {

        int a = 3;
        int b = 6;

        System.out.println("AND: " + (a & b));
        System.out.println("OR: " + (a | b));
        System.out.println("XOR: " + (a ^ b));
        System.out.println("NOT of a: " + (~a));
    }  
}
