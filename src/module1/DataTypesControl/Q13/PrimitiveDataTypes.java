package module1.DataTypesControl.Q13;

public class PrimitiveDataTypes {
    int a;
    float b;
    char c;
    byte d;

    short e;
    long f;
    double g;

    boolean h;

    public static void main(String[] args) {

        PrimitiveDataTypes pdt = new PrimitiveDataTypes();

        System.out.println("int: " + pdt.a);
        System.out.println("float: " + pdt.b);
        System.out.println("char: " + pdt.c);
        System.out.println("byte: " + pdt.d);

        System.out.println("short: " + pdt.e);
        System.out.println("long: " + pdt.f);
        System.out.println("double: " + pdt.g);
        
        System.out.println("boolean: " + pdt.h);
    }
}
